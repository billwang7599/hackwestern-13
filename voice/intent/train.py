"""Retrain the text -> intent classifier from phrases.txt, in one command.

    python3 voice/intent/train.py             # train, write intent_model.h, run the tests
    python3 voice/intent/train.py --no-test   # train + export only

Steps: read phrases.txt -> add simulated whisper mistakes (gen_data.py) ->
train -> write intent_model.h -> rebuild build/intent_cli -> run
tests/test_intent.py (held-out accuracy, confusion matrix, stop recall must be
100%, Python/C parity, latency). Exit code is non-zero if any test fails.

Model: multinomial logistic regression (softmax) on the hashed features from
intent.features() (char 2-4 grams + words, 4096 bins, L2-normalised), trained
full-batch with Adam + L2 weight decay. numpy only.

The header is the ONLY model file: intent.c #includes it and intent.py parses
it, so Python and C use the same (rounded) weights.

Thresholds are picked on a validation split carved out of the TRAIN templates
(never the test templates):
  threshold       max prob below this -> reject (LED no + BEEP 3)
  stop_threshold  classifier says "stop" with at least this -> S (stopping is
                  always safe, so this is deliberately low)
"""
from __future__ import annotations

import os
import random
import sys
import time

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_data  # noqa: E402
import intent as I  # noqa: E402

K = len(I.INTENTS)


def featurize(texts: list[str]):
    rows, cols, vals = [], [], []
    for r, t in enumerate(texts):
        _, toks = I.strip_wake(I.normalize(t))
        for k, v in I.features(toks).items():
            rows.append(r)
            cols.append(k)
            vals.append(v)
    return (np.array(rows, np.int64), np.array(cols, np.int64), np.array(vals, np.float64), len(texts))


def logits(X, W, b):
    rows, cols, vals, n = X
    Z = np.zeros((n, K))
    contrib = vals[:, None] * W[cols]            # nnz x K
    for k in range(K):
        Z[:, k] = np.bincount(rows, weights=contrib[:, k], minlength=n)
    return Z + b


def softmax(Z):
    Z = Z - Z.max(axis=1, keepdims=True)
    E = np.exp(Z)
    return E / E.sum(axis=1, keepdims=True)


def train(X, y, epochs=400, lr=0.05, l2=1e-4, seed=0):
    rows, cols, vals, n = X
    rng = np.random.default_rng(seed)
    W = rng.normal(0, 0.01, (I.N_FEAT, K))
    b = np.zeros(K)
    Y = np.eye(K)[y]
    # class weights: balance the classes so small ones (teach) aren't drowned out
    cw = n / (K * np.bincount(y, minlength=K).clip(1))
    sw = cw[y][:, None]
    mW, vW, mb, vb = 0, 0, 0, 0
    b1, b2, eps = 0.9, 0.999, 1e-8
    for ep in range(1, epochs + 1):
        P = softmax(logits(X, W, b))
        G = (P - Y) * sw / n                       # n x K
        gc = vals[:, None] * G[rows]               # nnz x K
        gW = np.zeros_like(W)
        for k in range(K):
            gW[:, k] = np.bincount(cols, weights=gc[:, k], minlength=I.N_FEAT)
        gW += l2 * W
        gb = G.sum(axis=0)
        mW = b1 * mW + (1 - b1) * gW; vW = b2 * vW + (1 - b2) * gW * gW
        mb = b1 * mb + (1 - b1) * gb; vb = b2 * vb + (1 - b2) * gb * gb
        W -= lr * (mW / (1 - b1 ** ep)) / (np.sqrt(vW / (1 - b2 ** ep)) + eps)
        b -= lr * (mb / (1 - b1 ** ep)) / (np.sqrt(vb / (1 - b2 ** ep)) + eps)
        if ep % 100 == 0:
            loss = -np.mean(np.log(P[np.arange(n), y] + 1e-12))
            print(f"  epoch {ep}: loss {loss:.4f}", flush=True)
    return W, b


def pick_threshold(P, y):
    """Highest-scoring cutoff: +1 per correct accept, -4 per wrong accept
    (a wrong move is worse than asking again)."""
    unk = I.INTENTS.index("unknown")
    best, best_t = -1e9, 0.5
    k = P.argmax(1)
    p = P.max(1)
    for t in np.arange(0.20, 0.91, 0.01):
        acc = (p >= t) & (k != unk)
        score = np.sum(acc & (k == y)) - 4 * np.sum(acc & (k != y))
        if score > best:
            best, best_t = score, float(t)
    return round(best_t, 2)


def cfloat(v, fmt: str) -> str:
    """C float literal: '1' -> '1.0f' (a bare integer + f is not valid C)."""
    t = format(float(v), fmt)
    if not any(ch in t for ch in ".en"):
        t += ".0"
    return t + "f"


def export_header(path, W, b, thr, stop_thr, info: str):
    Wr = np.float32(W.T)                           # K x N_FEAT
    br = np.float32(b)
    with open(path, "w") as f:
        f.write("/* GENERATED by voice/intent/train.py -- do not edit.\n")
        for line in info.strip().splitlines():
            f.write(f" * {line}\n")
        f.write(" */\n#ifndef INTENT_MODEL_H\n#define INTENT_MODEL_H\n\n")
        f.write(f"#define INTENT_N_FEAT {I.N_FEAT}\n#define INTENT_N {K}\n")
        f.write(f"#define INTENT_THRESHOLD {thr:.2f}f\n#define INTENT_STOP_THRESHOLD {stop_thr:.2f}f\n\n")
        f.write("static const char *const intent_names[INTENT_N] = {"
                + ", ".join(f'"{n}"' for n in I.INTENTS) + "};\n\n")
        f.write("static const float intent_b[INTENT_N] = {" + ", ".join(cfloat(v, ".6g") for v in br) + "};\n\n")
        f.write("static const float intent_W[INTENT_N][INTENT_N_FEAT] = {\n")
        for k in range(K):
            f.write(f"  /* {I.INTENTS[k]} */ {{")
            for i in range(0, I.N_FEAT, 16):
                f.write("\n    " + ",".join(cfloat(v, ".5g") for v in Wr[k, i:i + 16]) + ",")
            f.write("\n  },\n")
        f.write("};\n\n#endif\n")


def main():
    t0 = time.time()
    try:
        gen_data.load_phrases()
    except ValueError as e:
        sys.exit(f"phrases.txt has problems, fix them and rerun:\n{e}")
    rows = gen_data.generate(30, seed=13)
    train_rows = [(t, I.INTENTS.index(c)) for t, c, s in rows if s == "train"]
    random.Random(1).shuffle(train_rows)
    nval = len(train_rows) // 10
    val, tr = train_rows[:nval], train_rows[nval:]
    print(f"train {len(tr)}  val {nval}  (test templates held out: "
          f"{sum(1 for r in rows if r[2] == 'test')})")
    Xtr = featurize([t for t, _ in tr]); ytr = np.array([c for _, c in tr])
    Xva = featurize([t for t, _ in val]); yva = np.array([c for _, c in val])
    W, b = train(Xtr, ytr)
    Pva = softmax(logits(Xva, W, b))
    thr = pick_threshold(Pva, yva)
    stop_thr = 0.30
    acc_va = float(np.mean(Pva.argmax(1) == yva))
    info = (f"{len(tr)} train sentences (phrases.txt via gen_data.py, seed 13), {nval} validation.\n"
            f"Features: hashed char 2-4 grams + words, {I.N_FEAT} bins. Softmax regression, Adam, L2 1e-4.\n"
            f"Validation accuracy {acc_va:.4f}. threshold {thr:.2f} (picked on validation), stop_threshold {stop_thr:.2f}.")
    out = os.path.join(HERE, "intent_model.h")
    export_header(out, W, b, thr, stop_thr, info)
    print(info)
    print(f"wrote {out} ({os.path.getsize(out) // 1024} KB) in {time.time() - t0:.1f} s")
    if "--no-test" in sys.argv:
        return 0
    import subprocess
    voice = os.path.dirname(HERE)
    print("\nbuilding build/intent_cli and running tests/test_intent.py ...", flush=True)
    r = subprocess.run(["make", "-s", "-C", voice, "build/intent_cli"])
    if r.returncode:
        return r.returncode
    r = subprocess.run([sys.executable, os.path.join(voice, "tests", "test_intent.py")])
    print("\nRETRAIN OK: tests pass. Commit phrases.txt + intent_model.h." if r.returncode == 0
          else "\nRETRAIN FINISHED BUT TESTS FAIL (see FAIL lines above). Don't deploy this model.")
    return r.returncode


if __name__ == "__main__":
    sys.exit(main())
