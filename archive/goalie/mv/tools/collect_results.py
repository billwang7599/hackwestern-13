"""Collect out/sweep*.md (gitignored) into RESULTS.md (committed)."""
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
OUT = HERE / "out"


def rows(name):
    p = OUT / f"sweep{name}.md"
    return [l for l in p.read_text().splitlines() if l.startswith("| air") or l.startswith("| roll")] if p.exists() else []


def header(name):
    p = OUT / f"sweep{name}.md"
    return p.read_text().splitlines()[2] if p.exists() else ""


HDR = ("| mode | ball | dist m | speed m/s | fps | n | pred% | lead med cm | lead p90 cm | lead ok3 | "
       "lead ok10 | KF lead med | final med cm | final ok3 | |t| err ms | spd err |\n"
       "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")

parts = ["# goalie/mv synthetic accuracy results",
         "Generated by `python synth.py --sweep ...` then `python tools/collect_results.py`.",
         "Columns: pred% = shots with a prediction 150 ms before crossing; *lead* = error of that "
         "prediction (2D: X and height, cm); ok3 / ok10 = share within 3 / 10 cm; KF = constant-"
         "acceleration Kalman alternative; *final* = last frame before crossing; |t| = crossing-time "
         "error; spd = median SPEED-label error.",
         "", "## Air shots (thrown/kicked), main sweep", header("_air"), "", HDR, *rows("_air"),
         "", "![air](out/sweep_air_air.png) (regenerate locally; out/ is gitignored)",
         "", "## Rolling ball on the floor (ground-plane rays, Y fixed)", header("_roll"), "", HDR, *rows("_roll"),
         "", "## Ablations (tennis ball, 3 m, 30 fps, 40 shots per cell unless noted)", "", HDR]
for tag, label in [("_abl_base", "baseline (moments size, exposure = 1/fps)"),
                   ("_abl_ellipse", "fitEllipse minor axis instead of moments"),
                   ("_abl_exp4ms", "4 ms exposure (less blur)"),
                   ("_abl_clutter", "static orange clutter, static rejection only"),
                   ("_abl_clutter_bg", "static clutter + MOG2 motion mask")]:
    for r in rows(tag):
        parts.append(r.replace("| air |", f"| {label} |", 1))
parts += ["", "### Ball-size calibration error (pingpong+tennis, 60 fps, 24 shots)", "", HDR]
for tag, label in [("_abl_bias-0.05", "size -5%"), ("_abl_bias0", "size exact"), ("_abl_bias0.05", "size +5%")]:
    for r in rows(tag):
        parts.append(r.replace("| air |", f"| {label} |", 1))
(HERE / "RESULTS.md").write_text("\n".join(parts) + "\n")
print("wrote", HERE / "RESULTS.md")
